import { readFile, writeFile } from 'fs/promises';
import { existsSync } from 'fs';
import { join } from 'path';
import yaml from 'js-yaml';
import { JournalSystem } from '../journal/journalSystem';
import { getProjectPath } from '../core/utils/projectPath.js';

export interface ProjectSchema {
  project: {
    name: string;
    version: string;
    description?: string;
    last_updated: string;
    repository?: string;
  };
  
  architecture?: {
    type?: string;
    deployment?: string;
    frontend?: Record<string, string>;
    backend?: Record<string, string>;
    infrastructure?: Record<string, string>;
  };
  
  database?: {
    primary?: {
      type: string;
      name: string;
      host?: string;
    };
    tables?: Record<string, any>;
    cache?: Record<string, string>;
    queue?: Record<string, string>;
  };
  
  api?: {
    version?: string;
    base_url?: string;
    authentication?: string;
    endpoints?: Record<string, string[]>;
    webhooks?: string[];
  };
  
  security?: Record<string, any>;
  environments?: Record<string, any>;
  dependencies?: Record<string, any>;
  business_logic?: Record<string, any>;
  monitoring?: Record<string, any>;
  current_tasks?: Record<string, any>;
  known_issues?: any[];
  conventions?: Record<string, any>;
  resources?: Record<string, string>;
}

export class SchemaSystem {
  private schemaPath: string;
  private schema: ProjectSchema | null = null;
  private lastModified: Date | null = null;
  
  constructor(
    private journal: JournalSystem,
    private projectRoot: string = getProjectPath()
  ) {
    this.schemaPath = join(this.projectRoot, 'PROJECT_SCHEMA.yaml');
  }
  
  /**
   * Load project schema from file
   */
  async loadSchema(): Promise<ProjectSchema | null> {
    try {
      if (!existsSync(this.schemaPath)) {
        return null;
      }
      
      const content = await readFile(this.schemaPath, 'utf-8');
      const raw = yaml.load(content);
      // v9.3: Sanitize — strip numeric-string keys from corrupted files
      this.schema = (raw && typeof raw === 'object' && !Array.isArray(raw))
        ? this.stripNumericKeys(raw) as ProjectSchema
        : null;
      if (!this.schema) return null;
      this.lastModified = new Date();
      // Reads have no memory side effects: PROJECT_SCHEMA.yaml is the only copy (MEM-6)
      return this.schema;
    } catch (error) {
      await this.journal.logError({
        type: 'schema-load-error',
        error: (error as Error).message,
        context: `Failed to load schema from ${this.schemaPath}`,
        fixed: false,
        category: 'runtime'
      });
      return null;
    }
  }
  
  /**
   * Save project schema to file
   */
  async saveSchema(schema: ProjectSchema): Promise<void> {
    try {
      // v9.3: Runtime validation — prevent string-spread corruption
      if (!schema || typeof schema !== 'object' || Array.isArray(schema)) {
        throw new Error('saveSchema: schema must be a non-null object');
      }
      if (!schema.project || typeof schema.project !== 'object') {
        throw new Error('saveSchema: schema.project is required and must be an object');
      }
      
      // v9.3: Strip numeric-string keys from string-spread corruption
      const cleaned = this.stripNumericKeys(schema) as ProjectSchema;
      
      // Update timestamp
      cleaned.project.last_updated = new Date().toISOString();
      
      // Convert to YAML
      const yamlContent = yaml.dump(cleaned, {
        indent: 2,
        lineWidth: 120,
        noRefs: true
      });
      
      // Add header comment
      const header = `# PROJECT_SCHEMA.yaml - Generated by M7 MCP
# This file contains the complete project structure and configuration
# DO NOT EDIT MANUALLY - Use @m7 schema update instead
# Last updated: ${cleaned.project.last_updated}

`;
      
      await writeFile(this.schemaPath, header + yamlContent);
      this.schema = cleaned;
      this.lastModified = new Date();
      
      // Log the update
      await this.journal.logFeature({
        name: 'schema-updated',
        description: `Schema updated to version ${cleaned.project.version}`,
        implementation: 'SchemaSystem.saveSchema',
        lessons: ['Schema versioning helps track changes'],
        patterns: ['yaml-based-config'],
        complexity: 'light'
      });
      
    } catch (error) {
      await this.journal.logError({
        type: 'schema-save-error',
        error: (error as Error).message,
        context: `Failed to save schema to ${this.schemaPath}`,
        fixed: false,
        category: 'runtime'
      });
      throw error;
    }
  }
  
  /**
   * Initialize schema for a new project
   */
  async initializeSchema(projectName: string, description?: string): Promise<ProjectSchema> {
    const schema: ProjectSchema = {
      project: {
        name: projectName,
        version: '0.1.0',
        description: description || `${projectName} project`,
        last_updated: new Date().toISOString()
      }
    };
    
    await this.saveSchema(schema);
    return schema;
  }
  
  /**
   * Get current schema (cached)
   */
  getSchema(): ProjectSchema | null {
    return this.schema;
  }
  
  /**
   * Update a specific section of the schema
   */
  async updateSection(section: keyof ProjectSchema, data: any): Promise<void> {
    const current = await this.loadSchema();
    if (!current) {
      throw new Error('No schema found. Initialize project first.');
    }
    
    // Deep merge the section
    current[section] = this.deepMerge(current[section] || {}, data);
    
    await this.saveSchema(current);
  }
  
  /**
   * Check if database already exists
   */
  async checkDatabaseExists(): Promise<{ exists: boolean; name?: string; type?: string }> {
    const schema = await this.loadSchema();
    if (!schema?.database?.primary) {
      return { exists: false };
    }
    
    return {
      exists: true,
      name: schema.database.primary.name,
      type: schema.database.primary.type
    };
  }
  
  /**
   * Get all API endpoints
   */
  async getApiEndpoints(): Promise<Record<string, string[]> | null> {
    const schema = await this.loadSchema();
    return schema?.api?.endpoints || null;
  }
  
  /**
   * Validate schema against current codebase
   */
  async validateSchema(): Promise<{ valid: boolean; issues: string[] }> {
    const issues: string[] = [];
    const schema = await this.loadSchema();
    
    if (!schema) {
      return { valid: false, issues: ['No schema found'] };
    }
    
    // Check required fields
    if (!schema.project?.name) {
      issues.push('Project name is required');
    }
    
    if (!schema.project?.version) {
      issues.push('Project version is required');
    }
    
    // More validation can be added here
    
    return {
      valid: issues.length === 0,
      issues
    };
  }
  
  /**
   * Generate schema diff between current and new
   */
  async generateDiff(newSchema: Partial<ProjectSchema>): Promise<any> {
    const current = await this.loadSchema();
    if (!current) {
      return { added: newSchema, removed: {}, modified: {} };
    }
    
    // Simple diff implementation
    const diff = {
      added: {} as any,
      removed: {} as any,
      modified: {} as any
    };
    
    // TODO: Implement proper deep diff
    
    return diff;
  }
  
  /**
   * Deep merge helper
   */
  private deepMerge(target: any, source: any): any {
    const output = { ...target };
    
    if (this.isObject(target) && this.isObject(source)) {
      Object.keys(source).forEach(key => {
        if (this.isObject(source[key])) {
          if (!(key in target)) {
            output[key] = source[key];
          } else {
            output[key] = this.deepMerge(target[key], source[key]);
          }
        } else {
          output[key] = source[key];
        }
      });
    }
    
    return output;
  }
  
  private isObject(item: any): boolean {
    return item && typeof item === 'object' && !Array.isArray(item);
  }
  
  // v9.3: Strip numeric-string keys ('0', '1', '2', ...) from top level
  // These come from `{ ...jsonString }` spread — a corruption pattern
  private stripNumericKeys(obj: any): any {
    if (!obj || typeof obj !== 'object' || Array.isArray(obj)) return obj;
    const result: any = {};
    for (const key of Object.keys(obj)) {
      if (!/^\d+$/.test(key)) {
        result[key] = obj[key];
      }
    }
    return result;
  }
}
