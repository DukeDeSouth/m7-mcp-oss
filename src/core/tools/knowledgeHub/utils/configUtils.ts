/**
 * Configuration Utilities for Knowledge Hub
 * Handles loading, saving, and validating hub-config.yaml
 */

import * as path from 'path';
import * as yaml from 'js-yaml';
import {
  KnowledgeHubConfig,
  DocumentConfig,
  KnowledgeHubConfigSchema,
  DEFAULT_HUB_PATH,
  DEFAULT_DOCUMENTS,
  HUB_DIRECTORIES,
  CONFIG_FILE_NAME,
  KNOWLEDGE_HUB_VERSION,
  ValidationError
} from '../types.js';
import { safeReadFile, safeWriteFile, fileExists } from './fileUtils.js';

/**
 * Load configuration from hub-config.yaml
 */
export async function loadConfig(
  projectPath: string
): Promise<KnowledgeHubConfig> {
  const configPath = getConfigPath(projectPath);
  
  try {
    // Read config file
    const content = await safeReadFile(configPath);
    
    // Parse YAML (using safe load)
    const rawConfig = yaml.load(content);
    
    // Validate with Zod schema
    const config = KnowledgeHubConfigSchema.parse(rawConfig);
    
    return config as KnowledgeHubConfig;
  } catch (error: any) {
    if (error.name === 'ZodError') {
      throw new ValidationError(
        'Invalid configuration file',
        { errors: error.errors, configPath }
      );
    }
    
    throw error;
  }
}

/**
 * Save configuration to hub-config.yaml
 */
export async function saveConfig(
  projectPath: string,
  config: KnowledgeHubConfig
): Promise<void> {
  const configPath = getConfigPath(projectPath);
  
  try {
    // Validate before saving
    KnowledgeHubConfigSchema.parse(config);
    
    // Convert to YAML
    const yamlContent = yaml.dump(config, {
      indent: 2,
      lineWidth: 100,
      noRefs: true
    });
    
    // Add header comment
    const content = `# Knowledge Hub Configuration
# Auto-generated by M7 MCP Knowledge Hub v${KNOWLEDGE_HUB_VERSION}
# Last updated: ${new Date().toISOString()}

${yamlContent}`;
    
    // Write to file (atomic)
    await safeWriteFile(configPath, content);
  } catch (error: any) {
    if (error.name === 'ZodError') {
      throw new ValidationError(
        'Invalid configuration data',
        { errors: error.errors }
      );
    }
    
    throw error;
  }
}

/**
 * Check if Knowledge Hub is initialized
 */
export async function isInitialized(projectPath: string): Promise<boolean> {
  const configPath = getConfigPath(projectPath);
  return await fileExists(configPath);
}

/**
 * Generate default configuration
 */
export function generateDefaultConfig(): KnowledgeHubConfig {
  return {
    version: KNOWLEDGE_HUB_VERSION,
    initialized_at: new Date().toISOString(),
    hub_path: DEFAULT_HUB_PATH,
    auto_sync: {
      enabled: true,
      require_confirmation: true,
      triggers: {
        on_session_complete: true,
        on_schema_update: true,
        on_type_change: true,
        on_tool_add: true
      }
    },
    documents: DEFAULT_DOCUMENTS,
    versioning: {
      enabled: true,
      strategy: 'semantic',
      auto_commit: false,
      retain_versions: 10
    },
    migration: {
      backup_original: true,
      backup_location: '.m7/backups/knowledge-hub/',
      update_references: true
    }
  };
}

/**
 * Get config file path
 */
export function getConfigPath(projectPath: string): string {
  return path.join(projectPath, DEFAULT_HUB_PATH, 'config', CONFIG_FILE_NAME);
}

/**
 * Get hub root path
 */
export function getHubPath(projectPath: string): string {
  return path.join(projectPath, DEFAULT_HUB_PATH);
}

/**
 * Get document path (absolute)
 */
export function getDocumentPath(
  projectPath: string,
  documentPath: string
): string {
  return path.join(getHubPath(projectPath), documentPath);
}

/**
 * Get versions directory path
 */
export function getVersionsPath(
  projectPath: string,
  documentId?: string
): string {
  const basePath = path.join(getHubPath(projectPath), 'versions');
  
  if (documentId) {
    return path.join(basePath, documentId);
  }
  
  return basePath;
}

/**
 * Get backup directory path
 */
export function getBackupPath(projectPath: string): string {
  return path.join(projectPath, '.m7', 'backups', 'knowledge-hub');
}

/**
 * Validate configuration
 */
export function validateConfig(config: unknown): KnowledgeHubConfig {
  try {
    return KnowledgeHubConfigSchema.parse(config) as KnowledgeHubConfig;
  } catch (error: any) {
    throw new ValidationError(
      'Configuration validation failed',
      { errors: error.errors }
    );
  }
}

/**
 * Merge configuration updates
 */
export function mergeConfig(
  current: KnowledgeHubConfig,
  updates: Partial<KnowledgeHubConfig>
): KnowledgeHubConfig {
  return {
    ...current,
    ...updates,
    // Deep merge for nested objects
    auto_sync: {
      ...current.auto_sync,
      ...(updates.auto_sync || {})
    },
    versioning: {
      ...current.versioning,
      ...(updates.versioning || {})
    },
    migration: {
      ...current.migration,
      ...(updates.migration || {})
    },
    // Merge documents array
    documents: updates.documents || current.documents
  };
}

/**
 * Get all hub directories
 */
export function getHubDirectories(projectPath: string): string[] {
  return HUB_DIRECTORIES.map(dir => 
    path.join(getHubPath(projectPath), dir)
  );
}

/**
 * Check if auto-sync is enabled
 */
export function isAutoSyncEnabled(config: KnowledgeHubConfig): boolean {
  return config.auto_sync.enabled;
}

/**
 * Check if confirmation is required
 */
export function isConfirmationRequired(config: KnowledgeHubConfig): boolean {
  return config.auto_sync.require_confirmation;
}

/**
 * Get document config by ID
 */
export function getDocumentConfig(
  config: KnowledgeHubConfig,
  documentId: string
): DocumentConfig | undefined {
  return config.documents.find(doc => doc.id === documentId);
}

