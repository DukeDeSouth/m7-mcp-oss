/**
 * DCCE Renderer
 * 
 * Renders DCCE envelopes into platform-specific formats:
 * - github: Human View as markdown + AI View in HTML comment
 * - markdown: Human View + collapsible AI View (<details>)
 * - json: Full envelope as JSON
 * - plain: Human View only (graceful degradation)
 */

import { DCCEEnvelope, DCCERenderFormat, DCCERenderOptions } from './types.js';

/**
 * Render a DCCE envelope to the specified format
 */
export function renderEnvelope(
  envelope: DCCEEnvelope,
  options: DCCERenderOptions = { format: 'github' }
): string {
  switch (options.format) {
    case 'github':
      return renderGitHub(envelope, options);
    case 'markdown':
      return renderMarkdown(envelope, options);
    case 'json':
      return renderJSON(envelope);
    case 'plain':
      return renderPlain(envelope);
    default:
      return renderGitHub(envelope, options);
  }
}

/**
 * GitHub format:
 * Human View as plain markdown (top, always visible)
 * AI View as HTML comment (invisible in GitHub UI, accessible via API/source)
 */
function renderGitHub(envelope: DCCEEnvelope, options: DCCERenderOptions): string {
  const parts: string[] = [];
  
  // Human View — always first, always visible
  parts.push(envelope.channels.human);
  
  // AI View — hidden in HTML comment
  if (options.showAiView !== false) {
    parts.push('');
    parts.push('<!-- DCCE:AI-BEGIN');
    parts.push(JSON.stringify({
      dcceVersion: envelope.dcceVersion,
      id: envelope.id,
      contentType: envelope.contentType,
      ai: envelope.channels.ai,
      provenance: envelope.provenance,
    }, null, 2));
    parts.push('DCCE:AI-END -->');
  }
  
  return parts.join('\n');
}

/**
 * Markdown format:
 * Human View + collapsible <details> with AI View
 */
function renderMarkdown(envelope: DCCEEnvelope, options: DCCERenderOptions): string {
  const parts: string[] = [];
  
  // Human View
  parts.push(envelope.channels.human);
  
  // AI View in collapsible section
  if (options.showAiView !== false) {
    parts.push('');
    parts.push('<details>');
    parts.push('<summary>AI-assisted reasoning (optional)</summary>');
    parts.push('');
    parts.push('```json');
    parts.push(JSON.stringify(envelope.channels.ai, null, 2));
    parts.push('```');
    
    if (options.showProvenance && envelope.provenance) {
      parts.push('');
      parts.push(`*Generated by ${envelope.provenance.tool || 'unknown'} (${envelope.provenance.actor})*`);
    }
    
    parts.push('');
    parts.push('</details>');
  }
  
  return parts.join('\n');
}

/**
 * JSON format: Full envelope as-is
 */
function renderJSON(envelope: DCCEEnvelope): string {
  return JSON.stringify(envelope, null, 2);
}

/**
 * Plain format: Human View only (graceful degradation)
 */
function renderPlain(envelope: DCCEEnvelope): string {
  return envelope.channels.human;
}

/**
 * Extract DCCE AI View from GitHub-rendered text
 * (parses HTML comment block)
 */
export function extractAiView(text: string): Record<string, unknown> | null {
  const match = text.match(/<!-- DCCE:AI-BEGIN\s*([\s\S]*?)\s*DCCE:AI-END -->/);
  if (!match) return null;
  
  try {
    const parsed = JSON.parse(match[1]);
    return parsed.ai || parsed;
  } catch {
    return null;
  }
}

/**
 * Check if text contains a DCCE envelope
 */
export function hasDCCE(text: string): boolean {
  return /<!-- DCCE:AI-BEGIN/.test(text);
}
