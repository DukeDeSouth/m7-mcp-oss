/**
 * DCCE Policy Presets
 * 
 * Pre-configured policies for different OSS communities and contexts.
 */

import { DCCEPolicyPreset } from './types.js';

// Common AI-style anti-patterns in Human View
const COMMON_ANTI_PATTERNS: RegExp[] = [
  /^#{1,3}\s/m,                        // Markdown headers
  /^\s*[-*]\s/m,                       // Bullet lists
  /^\s*\d+\.\s/m,                      // Numbered lists
  /\|.*\|.*\|/,                        // Tables
  /#{2,}\s*(Summary|Changes|Test Plan|Overview)/i, // AI-section headers
  /Made with|Generated by|Powered by/i,  // AI footers
  /This PR (introduces|implements|adds|fixes|resolves)/i, // AI opener patterns
  /In this (pull request|PR|change)/i,   // AI opener patterns
];

export const POLICY_GENERIC_OSS: DCCEPolicyPreset = {
  name: 'generic-oss',
  description: 'Default policy for open-source contributions',
  policyHints: {
    maxHumanLength: 500,
    maxHumanSentences: 5,
    confidentiality: 'public',
  },
  humanViewAntiPatterns: COMMON_ANTI_PATTERNS,
  aiViewRequirements: {
    pr_description: ['intent', 'scope', 'testing'],
    issue_description: ['type', 'severity', 'reproduction'],
    changelog: ['version', 'changes'],
  },
};

export const POLICY_RUST_LANG: DCCEPolicyPreset = {
  name: 'rust-lang',
  description: 'Policy aligned with rust-lang/rust compiler-team#893',
  policyHints: {
    maxHumanLength: 400,
    maxHumanSentences: 4,
    confidentiality: 'public',
  },
  humanViewAntiPatterns: [
    ...COMMON_ANTI_PATTERNS,
    /\bAI\b|LLM|GPT|Claude|Cursor/i,      // Direct AI mentions
    /comprehensive|exhaustive|thorough/i,   // AI verbosity markers
    /\d+ test(s)? (pass|added|created)/i,   // Exact test counts
  ],
  aiViewRequirements: {
    pr_description: ['intent', 'scope', 'testing', 'rfc_reference'],
    issue_description: ['type', 'severity', 'reproduction', 'compiler_area'],
  },
};

export const POLICY_PRESETS: Record<string, DCCEPolicyPreset> = {
  'generic-oss': POLICY_GENERIC_OSS,
  'rust-lang': POLICY_RUST_LANG,
};

export function getPolicy(name: string): DCCEPolicyPreset {
  return POLICY_PRESETS[name] || POLICY_GENERIC_OSS;
}

export function listPolicies(): string[] {
  return Object.keys(POLICY_PRESETS);
}
